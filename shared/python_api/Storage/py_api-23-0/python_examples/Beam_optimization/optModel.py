def main(elems,eleCords,L,H,thresh,r,prevDel):
    
   
    delElems = {}

    print('-------------------OPT MODEL----------------------')
    nearNodes = {}
    maxSTR = max(list(elems.values()))
    for ids,val in elems.items():
        if not ids in prevDel:
            
            rr = float(val)/maxSTR
            
            #Nodes are not used in current config but kept to implement if wanted
            # n9 n8 n7
            # n6 n5 n4
            # n3 n2 n1  where n5 = cur element
            n1 = ids - L - 1
            n2 = ids - L 
            n3 = ids - L + 1
            n4 = ids - 1
            
            n6 = ids + 1
            n7 = ids + L - 1
            n8 = ids + L 
            n9 = ids + L + 1
            nearNodes[ids] = [n2, n4, n6, n8, n1,n3,n7,n9]
            
            
            densityF = getDensityFilter(ids,elems,eleCords, r,prevDel)
            
            rr = (densityF)*rr
            
            if rr<=thresh: #and not ids in [672,1824,624,1776]:
                delElems[ids]=val
                
                if ids > L*H:
                        if int(ids-L*H) in elems and not int(ids-L*H) in delElems :
                            delElems[ids-L*H] = 1
                        
                else:
                    if int(ids+L*H) in elems and not int(ids-L*H) in delElems :
                        delElems[ids+L*H] = 1  

    return delElems
   



        
