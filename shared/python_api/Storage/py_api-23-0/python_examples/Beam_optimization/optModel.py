def getDensityFilter(curEl,elems,elemCords, r,prevDel):
    
    
    H = 0
    hX = 0   
    for n in elemCords[curEl]['neighbors']:
        for ids,relem in n.items():
            H += max(0,r - relem)
            
            if not ids in prevDel:    
                hX += max(0,r - relem)
    
    return hX/H